CREATE TABLE IF NOT EXISTS DEMO_ASSET (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    ASSET_NAME VARCHAR(100) NOT NULL CHECK (CHAR_LENGTH(TRIM(ASSET_NAME)) > 0),
    NOTES VARCHAR(300),
    DELETED BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS SCAFFOLD_USER (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR(40) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR(100) NOT NULL,
    ENABLED BOOLEAN NOT NULL DEFAULT TRUE,
    CREDENTIAL_VERSION BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS SCAFFOLD_ROLE (
    CODE VARCHAR(32) PRIMARY KEY,
    NAME VARCHAR(80) NOT NULL
);

CREATE TABLE IF NOT EXISTS SCAFFOLD_USER_ROLE (
    USER_ID BIGINT NOT NULL REFERENCES SCAFFOLD_USER(ID),
    ROLE_CODE VARCHAR(32) NOT NULL REFERENCES SCAFFOLD_ROLE(CODE),
    PRIMARY KEY (USER_ID, ROLE_CODE)
);

CREATE TABLE IF NOT EXISTS SCAFFOLD_ROLE_PERMISSION (
    ROLE_CODE VARCHAR(32) NOT NULL REFERENCES SCAFFOLD_ROLE(CODE),
    PERMISSION VARCHAR(40) NOT NULL,
    PRIMARY KEY (ROLE_CODE, PERMISSION)
);
